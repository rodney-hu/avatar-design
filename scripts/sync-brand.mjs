/* Copies the web-ready brand files the /brand page shows from
   ../../05 Brand assets into site/src/brand/. Run `npm run sync:brand` after
   the logos or profile set change, then commit the result. Not part of
   `npm run build`: CI and Vercel only have this repo, so the copies are
   committed. Uses macOS `sips` to make 800 px JPEG previews of the profile set. */
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.resolve(root, '../../05 Brand assets');
const out = path.join(root, 'site/src/brand');
if (!existsSync(src)) { console.error(`Brand assets not found at ${src}`); process.exit(1); }

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

let n = 0;
for (const dir of ['horizontal', 'stacked', 'secondary', 'icon']) {
  for (const f of readdirSync(path.join(src, 'Logos', dir))) {
    if (!f.endsWith('.svg')) continue;
    if (dir === 'icon' && f.includes('-block-') && !f.endsWith('-fire.svg')) continue;
    cpSync(path.join(src, 'Logos', dir, f), path.join(out, f)); n++;
  }
}
const prof = path.join(src, 'Profile pics/Elemental');
for (const f of readdirSync(prof)) {
  if (!f.endsWith('-1x1.png')) continue;
  const dest = path.join(out, f.replace('-1x1.png', '-800.jpg'));
  execFileSync('sips', ['-Z', '800', '-s', 'format', 'jpeg', '-s', 'formatOptions', '82', path.join(prof, f), '--out', dest], { stdio: 'ignore' }); n++;
}
writeFileSync(path.join(out, 'README.md'), 'Generated by `npm run sync:brand` from `05 Brand assets/`. Do not edit; change the source and re-run.\n');
console.log(`synced ${n} files to site/src/brand`);
